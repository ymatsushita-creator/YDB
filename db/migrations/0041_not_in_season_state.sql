-- 0041 「この期の対象ではない」という状態
--
-- ★★ 訂正しても、一覧から消えていなかった。★★
--
--   期の判定を直す訂正（C-149 / C-157）は、打ち消し行に**元の状態を
--   そのままコピー**していた。打ち消し行それ自体が有効な出来事なので、
--   `v_person_approach_state` は**同じ期に同じ状態を返し続ける。**
--   実測で、表が「2期」と言っている **256 人が3期の一覧に残っていた。**
--
--   打ち消しは「その行を無かったことにする」だが、
--   **この製品の一覧は「最後の有効な出来事」で母集団を決める。**
--   だから打ち消しの行にも、意味のある状態を載せなければならない。
--
-- ★ 既存の終端状態（`declined` 見送り）は使わない。
--   「見送った」と「その期の対象ではなかった」は違う事実である。
--   運営が見送りの数を数えたときに、取り込みの訂正が混ざる。
--
-- ★ マスタは**追加と非活性化で運用する**（原則3）。0016 の行は動かさない。
--   `is_terminal = true` なので `v_headhunting_list` から自動的に外れる。
--
-- ★ 並びは 95 ―― 見送り（90）の後ろ。運用の状態遷移の末尾に置く。
-- ★ 冪等。
-- =============================================================

INSERT INTO approach_states (code, label, sort_order, is_terminal)
VALUES ('not_in_season', 'この期の対象ではない', 95, true)
ON CONFLICT (code) DO NOTHING;

COMMENT ON TABLE approach_states IS
    'アプローチ状態のマスタ。追加と非活性化で運用する（原則3）。'
    'not_in_season は「取り込みが別の期に付けていた」ことの訂正に使う（0041）。';
