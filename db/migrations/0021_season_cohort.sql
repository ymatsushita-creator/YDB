-- =============================================================
-- 0021 年度に「期」を持たせる
--
-- 発見の経緯: 実行⑨で依頼者から
-- **「学年というものはそもそも存在しない。1期、2期とあって、次の募集は3期」**
-- と指摘があった。
--
-- 画面はそれまで「学年（4年生・2026年卒）」を「記録層に無いもの」として
-- 出していたが、**無いのではなく、そもそも存在しない概念だった。**
-- 無い列を欲しがる注記は、次に触る人に「足りない実装」を作らせる。
--
-- ★ これは新しい事実ではない。**入れる場所が無かっただけである。**
--
-- `db/seeds/0002_season_2026.production.sql` には最初からこう書いてある ――
--
--   記録できなかったものが2つある。
--     1. 「NEO ACADEMIA 2期生」という名称。seasons に名前の列が無く、
--        enrollment_year（整数）しか持たない。期の呼び方は今は入らない
--
-- その1つ目をここで埋める。**2026年度 = 2期**は受領済みの事実であり、
-- 推測ではない。
--
-- ★ enrollment_year から導かない
--
-- 「年度の若い順に1,2,3…」と数えれば列は要らない。しかし
-- **募集を1年休んだ年があると番号がずれる。** 期は運営が数えるもので、
-- 暦から導けるものではない。導出にすると、休んだ年に黙って番号が動く。
--
-- ★ NULL 可にしてある
--
-- 本番（Supabase）にはすでに 2026 の行が入っている可能性がある。
-- NOT NULL を後から付けると、値の無い行があるだけで適用が止まる。
-- 期の分からない年度は NULL のままにし、画面は年度で代替表示する。
-- **分からないものを 0 期や 1 期で埋めない。**
-- =============================================================

ALTER TABLE seasons ADD COLUMN cohort_number integer;

COMMENT ON COLUMN seasons.cohort_number IS
    '期（1期・2期…）。運営が数える番号で、enrollment_year からは導けない'
    '（募集を休んだ年があると番号がずれる）。分からない年度は NULL。';

-- 0 期や負の期は存在しない。
ALTER TABLE seasons
    ADD CONSTRAINT seasons_cohort_positive
        CHECK (cohort_number IS NULL OR cohort_number > 0);

-- 同じ期が2つあると、画面のどちらを指しているか決まらない。
-- NULL は「まだ分からない」なので、重複を許す（部分一意）。
CREATE UNIQUE INDEX seasons_cohort_key
    ON seasons (cohort_number) WHERE cohort_number IS NOT NULL;

-- 受領済みの事実の反映。2026年度は NEO ACADEMIA 2期生（D-8）。
-- 実在するのはこの1行だけなので、ここで埋めても他の年度を巻き込まない。
UPDATE seasons SET cohort_number = 2 WHERE enrollment_year = 2026;
