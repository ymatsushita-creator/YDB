-- =============================================================
-- 0023 生年月日とメールを「無いこともある」に変える
--
-- 依頼者の指示（実行⑩）―― 2期の実データを入れる。
--
-- ★★ これは方針の変更である。★★
--   同じ実行の前半で、依頼者は「生年月日を集める」（記録層は変えない）を
--   選んでいた（C-61）。だが値は集まらず、投入の指示が繰り返された。
--   **指示が新しいほうを採る。** 経緯を消さないためにここへ書く。
--
-- 旧 NEO-Youth の 61 件は、こうなっている ――
--
--   55 件  氏名に姓と名の区切りが無い
--   61 件  生年月日の列そのものが無い
--   31 件  メールが無い
--   13 件  学校が無い
--
-- **無い値を作らない。** 埋めれば、その人について嘘の事実が1つ増える。
-- 「無い」を記録できる形にして、無いまま入れる。
--
-- ---------------------------------------------------------------
-- 同一人物の判定について
-- ---------------------------------------------------------------
-- `persons_match_keys_idx` は**一意制約ではなく検索用の索引**である
-- （0001:120）。もともと「3項目一致で自動紐づけ、部分一致は候補提示」を
-- **問い合わせ側で**行う設計で、記録層が一意性を保証してはいない。
--
-- したがって NULL を許しても、**壊れる保証は無い。**
-- ただし**照合の材料は減る。** 生年月日が無い人どうしは、
-- 氏名と学校だけで見分けることになる。
-- 名寄せするときは、材料が減っていることを前提に候補提示へ倒すこと。
--
-- ---------------------------------------------------------------
-- 学校とメールを、なぜ扱いを分けたか
-- ---------------------------------------------------------------
-- メール … NULL 可にする。無いことをそのまま持てる。
-- 学校   … NOT NULL のまま。9箇所が内部結合しており、NULL にすると
--          **学校の無い人が一覧から黙って消える**（INNER JOIN で落ちる）。
--          消えるのは、無いと書くより悪い。
--          代わりに「学校未記録」という非活性の行を1つ置き、そこへ寄せる
--          （原則3: 集計マスタは更新せず追加と非活性化で運用する）。
--          非活性なので、学校を選ぶ画面には出ない。
-- =============================================================

ALTER TABLE persons ALTER COLUMN birth_date DROP NOT NULL;
ALTER TABLE persons ALTER COLUMN email      DROP NOT NULL;

COMMENT ON COLUMN persons.birth_date IS
    '生年月日。旧システムから移した人は持っていないことがある（0023）。'
    'NULL は「まだ受け取っていない」であって「無い」ではない。';

COMMENT ON COLUMN persons.email IS
    'メール。旧システムから移した人は持っていないことがある（0023）。';


-- 学校が分からない人の置き場所。**非活性**なので選択肢には出ない。
-- 「学校未記録」という名前の学校に通っている、という意味ではない。
INSERT INTO schools (name, is_active)
VALUES ('学校未記録', false)
ON CONFLICT (name) DO NOTHING;


-- -------------------------------------------------------------
-- 取り込み元をたどれるようにする
-- -------------------------------------------------------------
-- 応募は `form_response_id` で辿れる（0001）。**人には無かった。**
-- 旧IDを持たせておくと、2回流しても人が二重にならず、
-- どの行から来たのかが後から分かる。
ALTER TABLE persons ADD COLUMN source_ref text;

CREATE UNIQUE INDEX persons_source_ref_key
    ON persons (source_ref) WHERE source_ref IS NOT NULL;

COMMENT ON COLUMN persons.source_ref IS
    '取り込み元の名指し（例 legacy:youth_candidates:42）。'
    '手で登録した人は NULL。2回流しても二重にならないための鍵。';


-- 変更ログ側も同じ形にする。**現在値が持てる値は、履歴も持てなければならない。**
-- ここを NOT NULL のままにすると、生年月日の無い人のプロフィールを
-- 編集した瞬間に、履歴の書き込みだけが落ちる。
ALTER TABLE person_profile_revisions ALTER COLUMN birth_date DROP NOT NULL;
ALTER TABLE person_profile_revisions ALTER COLUMN email      DROP NOT NULL;
