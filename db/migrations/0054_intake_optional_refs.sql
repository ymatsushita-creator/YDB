-- =============================================================
-- 0054 候補者の登録を「姓だけ必須」に変える
--
-- 依頼者の指示（2026-08-24）―― 表からの一括投入で 17 行が落ちた。
-- 落ちた理由は学校・流入元・入力者が未選択だったことで、判定は正しかった。
-- そのうえで依頼者は必須を外すことを選んだ ――
-- 「名前さえ入れてれば後は未記入でいいに決まってんだろ」。
--
-- ★★ これは方針の変更である。★★
--   0023 では生年月日とメールだけを「無いこともある」に変えた。
--   今回は**参照先そのもの**（学校・流入元・入力者）を任意にする。
--
-- ---------------------------------------------------------------
-- なぜ NOT NULL を外さないのか
-- ---------------------------------------------------------------
-- 外さない。0023 が学校について既に検討して却下している ――
--   `persons.school_id` を NULL 可にすると 9 箇所の内部結合で
--   **学校の無い人が一覧から黙って消える。** 消えるのは、無いと書くより悪い。
--
-- 同じ理屈が流入元にも効く ―― `touchpoints.channel_id` を空にできる形に
-- すると、接点そのものを作らない行が出る。すると流入元別の合計が候補者数より
-- 少なくなり、**ズレの原因が後から追えない。**
--
-- したがってこの2つは **記録層を変えず、非活性のプレースホルダ行へ寄せる。**
-- 0023 の「学校未記録」と同じやり方である（原則3: 集計マスタは更新せず
-- 追加と非活性化で運用する）。
--
-- ★ 非活性なので**選ぶ画面には出ない。** 運営が「不明」を選べるようにする
--   変更ではない。未選択のまま保存したときに、裏で寄せる先である。
-- ★ 名前を後から書き換えない。書き換えると過去の記録の意味が変わる。
--
-- 寄せ先（`is_active = false`）:
--   schools 「学校未記録」    … 0023 で既に置いた。ここでは作らない。
--   channels「流入元不明」    … ここで作る。
--
-- ---------------------------------------------------------------
-- 入力者だけは NULL 可にする（プレースホルダを作らない）
-- ---------------------------------------------------------------
-- `approach_events.recorded_by_staff_id` は **NULL 可にする。**
-- 学校や流入元と違い、**誰も内部結合していない** ――
--   `v_person_approach_state` / `v_headhunting_list` は列を通すだけで
--   `staffs` に結合しない（0016）。`src/queries/` は読んでもいない。
--   したがって NULL にしても**人は一覧から消えない。**
--
-- ★ 逆に「入力者未記録」という職員の行を1つ置くと**壊れる物がある** ――
--     tests/22_reference_season.test.ts  本番シードは `staffs` を0行に保つ
--                                        （氏名が push されるのを防ぐ壁）
--     tests/52_season3_alignment.test.ts 職員が1人でも居ると 0007 の
--                                        目標応募数の引き継ぎが走ってしまう
--   どちらも緩めてよい検査ではない。**居ない物を作らないほうが正しい。**
--
-- ★ `form_responses.matched_by_staff_id` は 0025 から既に NULL 可。
-- ★ `partner_recommendations.recorded_by_staff_id`（0035）は触らない。
--   あちらは画面が必ず職員を選ぶ。
--
-- 判定を外す側は `src/commands/intake.ts` の `addCandidate`。
-- 表（`/people/new`）と1人ずつの登録の**両方**が同じ関数を通るので、
-- 画面によって通る値が違う状態は作らない。
-- =============================================================

-- 流入元が分からない人の接点の置き場所。**非活性**なので選択肢には出ない。
-- 「流入元不明」というチャネルから来た、という意味ではない。
INSERT INTO channels (name, category, is_active)
VALUES ('流入元不明', 'unknown', false)
ON CONFLICT (name) DO NOTHING;

COMMENT ON TABLE channels IS
    '流入チャネル。`is_active = false` の「流入元不明」は、'
    '未選択のまま登録された接点の寄せ先である（0054）。'
    '選択肢には出ない。流入元別の集計では「不明」として現れる。';

-- 入力者を選ばずに登録できるようにする。**誰かを作らない。**
-- ★ 券（セッション）は staffId を持てるが、`app/login/actions.ts` は
--   `issueSession(secret, tier, Date.now())` と呼んで第4引数を渡していないので、
--   `currentStaffId()` は常に null である。つまり「いま入っている職員」に
--   寄せることは今日はできない。配線した日に、ここを見る前に券を見る。
ALTER TABLE approach_events ALTER COLUMN recorded_by_staff_id DROP NOT NULL;

COMMENT ON COLUMN approach_events.recorded_by_staff_id IS
    '記録した人。NULL は「誰が入れたか分からない」であって「誰も居ない」ではない（0054）。'
    'この列に結合している問い合わせは無いので、NULL でも人は一覧から消えない。';
