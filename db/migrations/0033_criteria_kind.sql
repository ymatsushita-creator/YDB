-- 0033 評価軸に「重み付け」を持たせる（必須の前提か、加点か）
--
-- 依頼者の指示（実行⑬の続き）――
--   「特別選考の重み付けはエクセルに従え」。
--
-- 応募管理表の「特別選考」シートは、9つの軸を**2段**で並べていた ――
--   基準設計（A〜C）        満たすべき前提。**必須**。
--   強く評価する条件（D〜I） 乗せる理由。**加点**。
-- これが運営の言う「重み付け」である。**数値の配点は表に無い**ので作らない
-- （満点は 4 のまま。C-105・面談シートも「点数＆コメント」の欄に文章しか無い）。
--
-- ★ 既存の軸（2期・最終面接の6軸など）は段分けを持たない。**既定は 'standard'**。
--   段を持つのは特別選考の9軸だけで、それは 0005 のシードと取り込みが入れる。
--
-- ★ この列は**表示のための区分**であって、集計には使わない。
--   確度・順位・合否は従来どおり点と通過で決まる（重みで自動加点しない。
--   「導出値を直接 UPDATE しない」と同じ精神で、重みを点へ勝手に変換しない）。
-- =============================================================

ALTER TABLE evaluation_criteria
    ADD COLUMN kind text NOT NULL DEFAULT 'standard',
    ADD CONSTRAINT evaluation_criteria_kind_chk
        CHECK (kind IN ('standard', 'required', 'strong'));
