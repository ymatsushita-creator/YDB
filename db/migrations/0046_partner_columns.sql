-- =============================================================
-- 0046 提携団体リストに、エクセルにあってDBに無かった枠を足す
--
-- 依頼者の指示（実行⑰）――「エクセルのアプローチリストから必要な枠を
-- 持ってきて」。
--
-- 応募管理表 `011_提携団体(学校ゼミ)リスト` の見出しと突き合わせた。
-- DBに無かったのは次のとおり ――
--   提携期日 / 推薦可能人数 / 最適連絡時期 / 所在地 /
--   アクションログ / メモ備考 / 関連するアカデミア生 /
--   興味のあるテーマ / SNS / 関連URL / AWARDへの応募有無
--
-- ★ **全部は足さない。** 足すのは、無いと運用が止まる4つに絞る ――
--     推薦可能人数  … 枠が何人かは、推薦枠ステイタスと対で要る
--     提携期日      … いつからの提携かで、今年声を掛ける相手が変わる
--     最適連絡時期  … 学校は時期を外すと年単位で待つことになる
--     所在地        … 訪問できる距離かどうかで動き方が変わる
--
--   残りを見送った理由は、**置き場所が別にあるか、まだ形が決まらないから**である。
--     アクションログ … 接点（`partner_reaches`）が既にその役をしている。
--                      1つの欄に積むと、いつ誰が当たったかが読めなくなる。
--     メモ備考／備考 … 2列とも自由記述で、分け方が記録に無い。
--     SNS／関連URL   … 複数本を1欄に入れると、後で1本ずつ辿れない。
--                      URLは表を分ける形が要る（まだ指示が無い）。
--     興味のあるテーマ・関連するアカデミア生・AWARD応募有無
--                    … 参照先（テーマ／候補者／応募）と結ぶべきもので、
--                      文字列で持つと**記録が二重になる。**
--
-- ★ どれも任意。**必須にしない** ―― 埋まっていない団体が170件のうち大半で、
--   必須にすると既存の行がどれも保存できなくなる。
-- =============================================================

ALTER TABLE partners
    -- 推薦可能人数。0 は「枠が無い」で、NULL は「聞いていない」。**別物である。**
    ADD COLUMN recommendation_seats integer,
    -- 提携した日。
    ADD COLUMN partnered_on         date,
    -- いつ連絡するのがよいか（「4月上旬」「学期末を避ける」など。自由記述）。
    ADD COLUMN best_contact_period  text,
    -- 所在地。住所そのものではなく、運用で使う粒度（市区まで）を想定する。
    ADD COLUMN location             text;

ALTER TABLE partners
    ADD CONSTRAINT partners_seats_not_negative
        CHECK (recommendation_seats IS NULL OR recommendation_seats >= 0);

COMMENT ON COLUMN partners.recommendation_seats IS
    '推薦可能人数。0（枠なし）と NULL（未確認）は別（C-180）。';
COMMENT ON COLUMN partners.best_contact_period IS
    '最適連絡時期。応募管理表 011 から（C-180）。';
