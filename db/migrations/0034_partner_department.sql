-- 0034 団体に「担当部署」と「社内担当」を持つ（応募管理表にあってDBに無かった）
--
-- 依頼者の指示（実行⑬）――「エクセルにある内容でDBにないものはないか（あれば追加して）」。
--
-- `011_提携団体(学校ゼミ)リスト` の列を1つずつ突き合わせ、**実データの入っている数**で
-- 足すかどうかを決めた。空の列を足しても、入れる場所が増えるだけで何も記録できない。
--
--   足した ――
--     担当部署   168/179 件。先方のどの部署か（企画部社会共創課連携推進係 など）
--     社内担当    41/179 件。NEO 側の受け持ち（櫻木 など）
--
--   足さなかった ――
--     所在地・SNS・関連URL        **0件**。列はあるが1件も入っていない
--     推薦可能人数                 2件。ほぼ空
--     ★ 最適連絡時期              138件あるが **126件が「1.0」** ―― 数字が入っており
--                                  何を指すのか読めない。**読めない値を意味のある列にしない。**
--     2期生推薦枠ステイタス        41件。4値（対象外／アポ実施済み／メール送信済み／未連絡）だが
--                                  **期ごとの状態**である。団体の現在値として持つと期をまたげない。
--     AWARDへの応募有無            160件。3値だが**特定のイベントへの参加**であって団体の属性ではない
--                                  （接点＝touchpoints で表すもの）
--     関連するアカデミア生          139件。**人への参照**を氏名の文字列で持つことになる
--   ―― 後ろの3つは置き場所を決める必要があるので、指示を仰いでから足す。
--
-- ★ どちらもマスタにしていない（自由入力）。したがって**集計できない**
--   ―― `engagement`（0031）・`staff_roles.role`（D-5）と同じ性質である。
--   数えたくなったら運営の語を受け取ってマスタへ移す。
--
-- ★ 空白の判定は 0015 の形（btrim の既定は半角スペースだけを落とす）。
-- =============================================================

ALTER TABLE partners
    ADD COLUMN contact_department text,
    ADD COLUMN internal_owner     text,
    ADD CONSTRAINT partners_contact_department_not_blank
        CHECK (contact_department IS NULL OR btrim(contact_department, E' \t\n\r　') <> ''),
    ADD CONSTRAINT partners_internal_owner_not_blank
        CHECK (internal_owner IS NULL OR btrim(internal_owner, E' \t\n\r　') <> '');
