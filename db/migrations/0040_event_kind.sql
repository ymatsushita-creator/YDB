-- 0040 イベントという種別を足す
--
-- 依頼者の指示（実行⑯）――「連携団体を追加タブの下に、イベントを追加タブを
-- 作成。これもスプシ形式で、内容はエクセルを見て決めろ」。
--
-- ★ 置き場所は**予定（0019）である。** 新しい表を作らない ――
--   イベントは「いつ・どこで・誰が対応する催し」で、予定と同じ形をしている。
--   別の表にすると、カレンダーが2つの表を混ぜて読むことになる。
--
-- ★ 既存の種別は6つとも**候補者が要る**か社内MTGで、
--   集客イベント（AWARD・説明会・応援カイギ）を置ける種別が無かった。
--   `requires_person = false` の種別を1つ足す。
--
-- ★ 並びは 60 ―― 面談（50）と社内MTG（90）の間。
--   マスタは追加と非活性化で運用する（原則3）。既存の行は動かさない。
--
-- ★ 冪等。符丁が既にあれば何もしない。
-- =============================================================

INSERT INTO appointment_kinds (code, label, sort_order, requires_person)
VALUES ('event', 'イベント', 60, false)
ON CONFLICT (code) DO NOTHING;
