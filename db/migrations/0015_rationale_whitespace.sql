-- =============================================================
-- 0015 根拠の必須が、空白の種類によって破れていた
--
-- 発見の経緯: E2（1軸だけ保存する）を作り、空の根拠が弾かれることを
-- テストで確かめようとしたら、**改行だけの根拠が保存できた。**
--
-- 原因は btrim の既定値である。
--
--   btrim(rationale) <> ''        -- 既定は半角スペースだけを落とす
--
-- `btrim(str)` は `btrim(str, ' ')` と同じで、**改行・タブ・全角スペースは
-- 落とさない。** つまり次の根拠はすべて通っていた。
--
--   E'\n'      改行だけ
--   E'\t'      タブだけ
--   '　'       全角スペースだけ（日本語入力では十分ありうる）
--
-- 原典はこう書いている（0001 のコメント）。
--
--   根拠エピソードの必須化は NOT NULL だけでは達成できない。
--   空文字が通ると「必須にした」という設計意図が形骸化する（資料5-3）。
--
-- **意図はそのとおりで、実装が届いていなかった。** 半角スペースだけを
-- 想定していた。画面から入力できるようになった以上、改行1つで
-- 「根拠あり」の記録ができる状態は残せない ―― ②（誰が何を評価したか）に
-- 答えるための列が、空白で埋まる。
--
-- これは「記録が実装より厳密に見える」形そのものである。B 節に
-- 「根拠は空にできない」と書いてあるのに、実際は空にできた。
--
-- 対応: 落とす文字を明示する。半角スペース・タブ・改行・復帰・全角スペース。
-- 0001 は適用済みなので編集せず、制約を差し替える。
--
-- 既存の行が違反しないことは、この後の `pnpm db:reset` と
-- tests/09（原典との定義の一致）で確かめている。デモの根拠はすべて実文である。
--
-- 元の制約は落とす。2つ残すと、どちらが効いているかが読んで分からない。
-- =============================================================

ALTER TABLE evaluation_scores
    DROP CONSTRAINT evaluation_scores_rationale_not_blank;

ALTER TABLE evaluation_scores
    ADD CONSTRAINT evaluation_scores_rationale_not_blank
        CHECK (btrim(rationale, E' \t\n\r　') <> '');

COMMENT ON COLUMN evaluation_scores.rationale IS
    '点の根拠。空にできない。空白の判定は半角スペース・タブ・改行・復帰・'
    '全角スペースを落としてから行う（0015。btrim の既定は半角スペースだけ）。';
