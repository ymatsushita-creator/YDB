-- =============================================================
-- 0050 KPIの変数に、確度別の人数を足す
--
-- 依頼者の指示（実行⑰）――「KPIはS、A以上、B以上確度別の人数も入れて」。
--
-- ★ 「A以上」「B以上」は**段階の順**で数える（`confidence_grades.sort_order`）。
--   S=1 / A=2 / B=3 / C=4 なので、「A以上」は sort_order <= 2 である。
--   ★ 記号を並べて書かない（'S','A' のような列挙にしない）――
--     段階が増えたとき、列挙は黙って取りこぼす。順で書けば追従する。
--
-- ★ 期ごとに数える。確度は期に属する（0039）。
-- ★ 「S」だけは**その段階ちょうど**。以上ではない（依頼者の書き分けのまま）。
-- =============================================================

INSERT INTO kpi_metrics (key, label, definition, unit, sort_order) VALUES
  ('confidence_s',  '確度S',
   'その期に確度Sが記入されている人数。Sちょうど（以上ではない）。', '人', 7),
  ('confidence_a',  '確度A以上',
   'その期に確度SまたはAが記入されている人数。', '人', 8),
  ('confidence_b',  '確度B以上',
   'その期に確度S・A・Bのいずれかが記入されている人数。', '人', 9)
ON CONFLICT (key) DO NOTHING;
