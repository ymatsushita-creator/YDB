-- =============================================================
-- 0024 職員のメールを「無いこともある」に変える
--
-- 依頼者の指示（実行⑩）―― 実データを画面に出す。
--
-- ヘッドハンティングとボーダーラインの一覧は `v_headhunting_list`、
-- つまり**アプローチ状態の記録がある人**だけを出す。
-- 記録するには `approach_events.recorded_by_staff_id`（職員）が要るが、
-- 本番に職員が1人も居なかった。
--
-- 旧システムには担当者の**氏名だけ**がある（メールは無い）。
-- **無いものを作らない。** メールを NULL 可にして、氏名だけで入れる。
--
-- ★ 一意制約は NULL を別物として扱うので、メールの無い職員が
--   何人居ても衝突しない（`staffs_email_key`）。
--   同姓同名の職員を見分ける手段は氏名しか無くなるが、
--   **持っていない値を作るよりはよい。**
-- =============================================================

ALTER TABLE staffs ALTER COLUMN email DROP NOT NULL;

COMMENT ON COLUMN staffs.email IS
    'メール。旧システムから移した職員は持っていないことがある（0024）。';
