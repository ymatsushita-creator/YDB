-- -------------------------------------------------------------
-- 辞退理由
-- -------------------------------------------------------------
-- 「未確認」だけは最初から要る。
--
-- status_histories.withdraw_reason_id は withdraw のとき NOT NULL である
-- （0008）。理由が分からないまま辞退を記録する場面は必ずあるので、
-- 受け皿が無いと辞退そのものを記録できなくなる。
--
-- NULL を許さないのは、「まだ聞けていない」と「本当に理由がない」を
-- 集計で区別できなくするため。理由不明も1つの事実として記録する
-- （原則7: 事実の有無で判定し、理由で分岐しない）。
--
-- 「未確認」が分布のどれだけを占めるかは、そのまま運用の質を表す。
-- 分布から消えていると、聞けていないことに誰も気づけない。
INSERT INTO withdraw_reasons (code, label, is_active)
VALUES ('unconfirmed', '未確認', true)
ON CONFLICT (code) DO NOTHING;


