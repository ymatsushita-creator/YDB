-- -------------------------------------------------------------
-- 2026年度（NEO ACADEMIA 2期生）
-- -------------------------------------------------------------
-- 出所は旧 NEO-Youth の DB とコードの読み取り（2026-08-07 受領）。
-- 一覧と受け取りの経緯は docs/pilot/DATA-QUESTIONS.md、
-- 判断の理由は db/DECISIONS.md D-8 にある。
--
-- ★★ 4つの日付のうち2つは推測値である。★★
--
--   outreach_start_date  2026-02-01  1次面談の開始日。★これを集客起点に充てた
--   application_open_date 2026-03-10 応募フォームの受付開始。確定
--   application_close_date 2026-03-22 ★推測。締切は DB にもコードにも無い。
--                                      実績の最終応募日を締切と見なしている
--   selection_end_date   2026-04-15  合否通知・入金案内の日。確定した日付を
--                                    「選考終了」に充てた（充て方は判断）
--
-- 推測値をここに書くのは、CLAUDE.md 9節「未確定の値をたぶんこうだろうで
-- 埋めない」に反する。それでも入れているのは、依頼者が推測と明示したうえで
-- 置くと決めたためで、**由来を消さないことを条件にしている。**
-- 実際の締切が判明したら season_revisions に変更履歴を残して直す（原則4）。
-- 日付は集計定義そのものなので、黙って上書きしない。
--
-- 記録できなかったものが2つある。
--   1. 「NEO ACADEMIA 2期生」という名称。seasons に名前の列が無く、
--      enrollment_year（整数）しか持たない。期の呼び方は今は入らない
--   2. 「選考開始 2026-03-23」。seasons は4つの日付しか持たない。
--      応募締切と選考終了の間に選考開始は無い
--
-- 定員36・目標応募数100は 2026-08-07 に実数値として受領済み（D-8）。
INSERT INTO seasons (
    enrollment_year,
    outreach_start_date,
    application_open_date,
    application_close_date,
    selection_end_date,
    target_application_count,
    capacity
)
VALUES (
    2026,
    DATE '2026-02-01',
    DATE '2026-03-10',
    DATE '2026-03-22',   -- ★推測
    DATE '2026-04-15',
    100,
    36
)
ON CONFLICT (enrollment_year) DO NOTHING;


-- -------------------------------------------------------------
-- 選考ステップ
-- -------------------------------------------------------------
-- 旧システムの状態遷移は8つあった。
--
--   応募前 → 応募完了 → 書類選考 → グループ面接 → 最終面接
--          → 合格予定 → 合格／補欠合格 → 承諾書提出
--
-- **このうちステップは4つだけである。** 残りは結果か状態であって、
-- 選考の段ではない。合格・補欠合格・辞退・保留・承諾書提出を
-- selection_steps に混ぜると、「最終ステップを通過したら合格」という
-- 判定（sort_order の最大）が壊れる ―― 合格そのものが段になるため、
-- 通過しても次の段が残る。
--
-- 「応募前」も入れない。応募がまだ無い状態にステップは付かない。
--
-- sla_days と pass_criteria は入れていない。**どちらも運用時に決める値で、
-- 旧システムに記録が無い。** 推測で入れると SLA 超過の警告が
-- 根拠のない日数で鳴りはじめる。
INSERT INTO selection_steps (season_id, sort_order, name)
SELECT s.id, v.sort_order, v.name
FROM   seasons s
CROSS JOIN (VALUES
    (1, '応募受付'),
    (2, '書類選考'),
    (3, 'グループ面接'),
    (4, '最終面接')
) AS v(sort_order, name)
WHERE  s.enrollment_year = 2026
ON CONFLICT (season_id, sort_order) DO NOTHING;


-- -------------------------------------------------------------
-- 評価の観点（最終面接の6軸）
-- -------------------------------------------------------------
-- evaluation_criteria は年度ではなく**ステップに属する**（selection_step_id）。
-- 6軸は最終面接の軸である。旧 DB では candidates.sec2_* に入っていたが、
-- あの表は最終面接シートであり、列名の "sec2" は旧システムの呼び名にすぎない。
--
-- 各4点満点。合計24点満点。旧システムの最終面接テーブルにも
-- 各項目を1〜4に制限する制約があり、実データも全行が1〜4に収まっている。
-- **満点は依頼者に確認して確定した。** 実データの最大値から推定したのではない
-- （実測の最大が満点である保証は無い ―― doc_score がその例で、
-- 実測13・満点16だった）。
--
-- 名前は運営が使っている日本語をそのまま置く。英語の列名
-- （smile / respect / premise / passion / thinking / honest）へ寄せない。
-- 運営の言葉をこちらの語に翻訳して記録しない（Pilot Rule）。
--
-- **書類選考の軸は入れていない。** 満点16は確定しているが、
-- 旧システムは doc_score という1つの数値しか持たず、**軸の呼び名が無い。**
-- こちらで名付けると、運営が使っていない語がマスタとして固定化する
-- （原則3: 集計マスタは更新せず追加と非活性化で運用する）。
-- 呼び名を確認してから足す。
--
-- グループ面接の軸も入れていない。旧データに点が無い
-- （sec2_group は A〜E の組分けで、評価ではない）。
INSERT INTO evaluation_criteria (selection_step_id, name, scale_max, sort_order)
SELECT st.id, v.name, 4, v.sort_order
FROM   selection_steps st
JOIN   seasons s ON s.id = st.season_id
CROSS JOIN (VALUES
    (1, '笑顔'),
    (2, 'リスペクト'),
    (3, '前提超越'),
    (4, '熱量'),
    (5, '地頭力'),
    (6, '素直さ')
) AS v(sort_order, name)
WHERE  s.enrollment_year = 2026
  AND  st.name = '最終面接'
ON CONFLICT (selection_step_id, sort_order) DO NOTHING;


