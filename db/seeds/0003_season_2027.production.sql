-- =============================================================
-- 実在する期 ―― 3期（2027年度）
--
-- 依頼者の指示（実行⑨）――「次は三期だから、三期も作って」。
--
-- ★★★ このファイルの日付は**4つとも推測値である。** ★★★
--
-- 3期の日程は受領していない。しかし `seasons` の4つの日付は NOT NULL で、
-- 行を作るには何かを入れるしかない。**依頼者が作れと指示したので作る**が、
-- `CLAUDE.md` の「記録にない値の創作」に触れる以上、
-- **由来を消さないことを条件にする。** これは 0002（2026年度）で
-- 応募締切を推測で置いたときと同じ扱いである。
--
-- 推測の根拠は1つだけ ―― **2期の周期をそのまま1年ずらした。**
--
--   2期(2026)  集客 02-01 / 応募開始 03-10 / 応募締切 03-22 / 選考終了 04-15
--   3期(2027)  集客 02-01 / 応募開始 03-10 / 応募締切 03-22 / 選考終了 04-15
--
-- **周期が変わらないという保証はどこにも無い。** 実際の日程が分かったら
-- `season_revisions` に変更履歴を残して直す（原則4）。
-- 日付は集計定義そのものなので、黙って上書きしない。
--
-- ★ 定員 36 は受領した実数値である（2026-08-10）。**推測ではない。**
--   目標応募数は受け取っていないので NULL のまま。
--   2期の 100 を今期の数字として写さない。
--
-- ★ 選考ステップは受領した（2026-08-10）。**3本である。**
--
--     書類審査（1次面接） → グループ面接（2次面接） → 最終面接（3次面接）
--
--   ここには2つ、2期との違いがある。**どちらも黙って揃えない。**
--
--     1. 2期は4本で、先頭に「応募受付」があった。3期の指定には無い
--     2. 2期の1本目は「書類選考」だが、3期の指定は**「書類審査」**である
--
--   運営の言葉をこちらの語に翻訳して記録しない（Pilot Rule）。
--   同じものを指しているのかは確認していないので、受け取った語をそのまま置く。
--   括弧の「N次面接」は並び順のことなので、sort_order で表す。
--
-- ★ 評価軸は入れていない。3期の軸は受け取っていない。
--   2期の6軸を写すと、変わっていた場合に**運営が使っていない軸**が
--   マスタとして固定化する（原則3）。
-- =============================================================

INSERT INTO seasons (
    enrollment_year,
    cohort_number,
    outreach_start_date,
    application_open_date,
    application_close_date,
    selection_end_date,
    target_application_count,
    capacity
)
VALUES (
    2027,
    3,
    DATE '2027-02-01',   -- ★推測。2期の集客起点を1年ずらした
    DATE '2027-03-10',   -- ★推測。同上
    DATE '2027-03-22',   -- ★推測。同上（2期の締切自体も推測値）
    DATE '2027-04-15',   -- ★推測。同上
    NULL,                -- 目標応募数は未受領。前期の 100 を写さない
    36                   -- 定員。受領した実数値（2026-08-10）
)
ON CONFLICT (enrollment_year) DO NOTHING;


-- すでに行がある本番のために、空欄だけを埋める。
-- **すでに値が入っているものは上書きしない**（後から直した値を消さないため）。
UPDATE seasons SET capacity = 36
 WHERE cohort_number = 3 AND capacity IS NULL;


-- -------------------------------------------------------------
-- 選考ステップ（受領。2026-08-10）
-- -------------------------------------------------------------
-- SLA と通過基準は入れていない。運用時に決める値で、まだ受け取っていない
-- （2期でも同じ理由で空にしてある）。
INSERT INTO selection_steps (season_id, sort_order, name)
SELECT s.id, v.sort_order, v.name
FROM   seasons s
CROSS JOIN (VALUES
    (1, '書類審査'),
    (2, 'グループ面接'),
    (3, '最終面接')
) AS v(sort_order, name)
WHERE  s.cohort_number = 3
ON CONFLICT (season_id, sort_order) DO NOTHING;
