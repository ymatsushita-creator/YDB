/**
 * 打たれた文字の扱いを1箇所に置く（C-126）。
 *
 * ★ **落とす空白は、制約と同じ集合にする。** `btrim` の既定は半角空白だけで、
 *   日本語入力では全角空白（U+3000）が素直に混ざる。集合がずれると
 *   「見えない値が静かに溜まる」 ―― 0015 で制約に入れ、C-119 で表の保存に入れ、
 *   **それでも `profile.ts` だけがずれていた**（フォームから打つと全角空白が残った）。
 *
 * ★ 同じ集合を3箇所に書き写していたのが根である。**定義は1つ。**
 *   SQL へ渡すときはパラメータで渡す（`btrim($1, $2)`）。
 *
 * ★ JS の `trim()` はこの集合を含む（全角空白も落とす）ので、
 *   判定に `trim()`、保存に `btrim(既定)` を使うと**通ってから残る。**
 *   保存側は必ずこの集合を渡す。
 */
export const BLANK_CHARS = ' \t\n\r　'

/** 空白だけなら null。**記録に空文字を置かない**（無いことは NULL で表す）。 */
export const blank = (v: string | null | undefined): string | null =>
  ((v ?? '').trim() || null)
